#!/usr/bin/env python3
"""Report or remove obsolete PCEP backend rollback image tags safely."""

import argparse
from dataclasses import dataclass
import importlib.util
import json
from pathlib import Path
import re
import subprocess


def load_operation_lock():
    path = Path(__file__).with_name('operation_lock.py')
    spec = importlib.util.spec_from_file_location('pcep_operation_lock', path)
    if spec is None or spec.loader is None:
        raise RuntimeError('Cannot load the operation-lock implementation.')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


operation_lock = load_operation_lock()
OperationLockError = operation_lock.OperationLockError
exclusive_operation_lock = operation_lock.exclusive_operation_lock


ROLLBACK_REPOSITORY = 'pcep-backend-rollback'
IMAGE_ID_PATTERN = re.compile(r'^sha256:[0-9a-f]{64}$')
CONTAINER_ID_PATTERN = re.compile(r'^[0-9a-f]{64}$')
RELEASE_PATTERN = r'[A-Za-z0-9][A-Za-z0-9._-]{0,63}'
TAG_PATTERN = re.compile(
    rf'^(?P<stamp>\d{{8}}T\d{{6}}Z)-release-(?P<release>{RELEASE_PATTERN})$'
)
SENSITIVE_IMAGE_ENV_PREFIXES = (
    'CORS_',
    'DATABASE_',
    'DJANGO_',
    'PCEP_APP_',
    'POSTGRES_',
)
SENSITIVE_IMAGE_ENV_NAMES = {'ACCESS_TOKEN', 'PASSWORD', 'SECRET_KEY'}
MINIMUM_VALID_IMAGES = 2


class ImageRetentionError(RuntimeError):
    pass


@dataclass(frozen=True)
class RollbackImage:
    tag: str
    reference: str
    image_id: str


def keep_count(value):
    try:
        count = int(value)
    except (TypeError, ValueError) as error:
        raise argparse.ArgumentTypeError('keep must be an integer') from error
    if not MINIMUM_VALID_IMAGES <= count <= 100:
        raise argparse.ArgumentTypeError(
            f'keep must be between {MINIMUM_VALID_IMAGES} and 100'
        )
    return count


def run_command(command, *, timeout=60):
    try:
        result = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except FileNotFoundError as error:
        raise ImageRetentionError(f'Required executable is missing: {command[0]}') from error
    except subprocess.TimeoutExpired as error:
        raise ImageRetentionError(f'Command timed out: {command[0]}') from error
    if result.returncode:
        detail = result.stderr.strip()[-2000:] or result.stdout.strip()[-2000:]
        raise ImageRetentionError(
            f'Command failed ({result.returncode}): {command[0]}: {detail}'
        )
    return result.stdout.strip()


def discover_rollback_tags(runner=run_command):
    output = runner(
        [
            'docker',
            'image',
            'ls',
            '--filter',
            f'reference={ROLLBACK_REPOSITORY}:*',
            '--no-trunc',
            '--format',
            '{{json .}}',
        ]
    )
    discovered = []
    seen_tags = set()
    for line in output.splitlines():
        try:
            item = json.loads(line)
        except json.JSONDecodeError as error:
            raise ImageRetentionError('Docker returned invalid image-list JSON.') from error
        if not isinstance(item, dict) or item.get('Repository') != ROLLBACK_REPOSITORY:
            raise ImageRetentionError('Docker returned an image outside the rollback repository.')
        tag = item.get('Tag')
        image_id = item.get('ID')
        if (
            not isinstance(tag, str)
            or not tag
            or tag in seen_tags
            or not isinstance(image_id, str)
            or not IMAGE_ID_PATTERN.fullmatch(image_id)
        ):
            raise ImageRetentionError('Docker returned unsafe rollback tag metadata.')
        seen_tags.add(tag)
        discovered.append(
            RollbackImage(tag, f'{ROLLBACK_REPOSITORY}:{tag}', image_id)
        )
    return sorted(discovered, key=lambda image: image.tag, reverse=True)


def inspect_metadata(reference, runner=run_command):
    payload = runner(['docker', 'image', 'inspect', reference])
    try:
        images = json.loads(payload)
        if not isinstance(images, list) or len(images) != 1:
            raise ValueError
        metadata = images[0]
        if not isinstance(metadata, dict):
            raise ValueError
        return metadata
    except (TypeError, ValueError, json.JSONDecodeError) as error:
        raise ImageRetentionError('Rollback image has invalid inspection metadata.') from error


def validate_rollback_image(candidate, metadata):
    match = TAG_PATTERN.fullmatch(candidate.tag)
    if not match:
        raise ImageRetentionError('Tag was not generated by the current deploy contract.')
    try:
        image_id = metadata['Id']
        config = metadata['Config']
        user = config['User']
        environment = config['Env']
        labels = config['Labels']
    except (KeyError, TypeError) as error:
        raise ImageRetentionError('Rollback image is missing required metadata.') from error
    if image_id != candidate.image_id or not IMAGE_ID_PATTERN.fullmatch(image_id):
        raise ImageRetentionError('Rollback tag resolved to an inconsistent image ID.')
    if user != 'appuser':
        raise ImageRetentionError('Rollback image does not run as appuser.')
    if (
        not isinstance(environment, list)
        or not all(isinstance(entry, str) and '=' in entry for entry in environment)
        or not isinstance(labels, dict)
    ):
        raise ImageRetentionError('Rollback image has invalid runtime metadata.')

    environment_names = [entry.split('=', 1)[0] for entry in environment]
    sensitive = sorted(
        name
        for name in environment_names
        if name in SENSITIVE_IMAGE_ENV_NAMES
        or name.startswith(SENSITIVE_IMAGE_ENV_PREFIXES)
    )
    if sensitive:
        raise ImageRetentionError(
            'Rollback image embeds runtime secret keys: ' + ', '.join(sensitive)
        )
    releases = [
        entry.split('=', 1)[1]
        for entry in environment
        if entry.startswith('PCEP_RELEASE=')
    ]
    expected_release = match.group('release')
    if (
        len(releases) != 1
        or releases[0] != expected_release
        or labels.get('org.opencontainers.image.revision') != expected_release
    ):
        raise ImageRetentionError('Rollback release metadata does not match its tag.')
    return expected_release


def container_ids(runner=run_command):
    output = runner(
        ['docker', 'container', 'ls', '--all', '--quiet', '--no-trunc']
    )
    identifiers = [line for line in output.splitlines() if line]
    if any(not CONTAINER_ID_PATTERN.fullmatch(identifier) for identifier in identifiers):
        raise ImageRetentionError('Docker returned an unsafe container ID.')
    return identifiers


def container_image_ids(runner=run_command):
    identifiers = container_ids(runner)
    images = set()
    for identifier in identifiers:
        try:
            image_id = runner(
                [
                    'docker', 'container', 'inspect', '--format', '{{.Image}}',
                    identifier,
                ]
            )
        except ImageRetentionError:
            # Shared-host maintenance containers can legitimately disappear
            # between list and inspect. Ignore only a confirmed disappearance;
            # a persistent container or unrelated inspect failure stays fatal.
            if identifier not in container_ids(runner):
                continue
            raise
        if not IMAGE_ID_PATTERN.fullmatch(image_id):
            raise ImageRetentionError('Docker returned an unsafe container image ID.')
        images.add(image_id)
    return images


def image_has_containers(image_id, runner=run_command):
    if not IMAGE_ID_PATTERN.fullmatch(image_id):
        raise ImageRetentionError('Refusing an unsafe image ID use check.')
    output = runner(
        [
            'docker', 'container', 'ls', '--all', '--quiet', '--no-trunc',
            '--filter', f'ancestor={image_id}',
        ]
    )
    container_ids = [line for line in output.splitlines() if line]
    if any(not CONTAINER_ID_PATTERN.fullmatch(identifier) for identifier in container_ids):
        raise ImageRetentionError('Docker returned an unsafe container ID.')
    return bool(container_ids)


def retention_plan(candidates, metadata_loader, in_use_image_ids, keep=5):
    keep = keep_count(keep)
    candidates = sorted(candidates, key=lambda image: image.tag, reverse=True)
    valid = []
    invalid = {}
    for candidate in candidates:
        try:
            validate_rollback_image(candidate, metadata_loader(candidate.reference))
        except (ImageRetentionError, OSError, ValueError) as error:
            invalid[candidate.reference] = str(error)
        else:
            valid.append(candidate)
    if len(valid) < MINIMUM_VALID_IMAGES:
        raise ImageRetentionError(
            f'Only {len(valid)} rollback image(s) satisfy the current deploy contract; '
            f'at least {MINIMUM_VALID_IMAGES} are required before pruning.'
        )

    retained = valid[:keep]
    retained_references = {candidate.reference for candidate in retained}
    removals = [
        candidate
        for candidate in candidates
        if candidate.reference not in retained_references
    ]
    in_use_removals = [
        candidate.reference
        for candidate in removals
        if candidate.image_id in in_use_image_ids
    ]
    if in_use_removals:
        raise ImageRetentionError(
            'Refusing to remove rollback tags used by containers: '
            + ', '.join(in_use_removals)
        )
    return {'keep': retained, 'remove': removals, 'invalid': invalid}


def _execute_unlocked(*, keep=5, apply=False, runner=run_command):
    candidates = discover_rollback_tags(runner)
    in_use = container_image_ids(runner)
    plan = retention_plan(
        candidates,
        lambda reference: inspect_metadata(reference, runner),
        in_use,
        keep,
    )
    print(
        f'{"Applying" if apply else "Dry run:"} keep up to the newest {keep} '
        'verified backend rollback images.'
    )
    print(
        f'rollback tags: keep {len(plan["keep"])} valid, '
        f'remove {len(plan["remove"])} '
        f'({len(plan["invalid"])} invalid under the current contract)'
    )
    for candidate in plan['keep']:
        print(f'  KEEP   {candidate.reference} ({candidate.image_id})')
    for candidate in plan['remove']:
        reason = plan['invalid'].get(candidate.reference)
        detail = f' [INVALID: {reason}]' if reason else ''
        print(f'  REMOVE {candidate.reference} ({candidate.image_id}){detail}')
    if not apply:
        print('Nothing removed. Re-run with --apply only after reviewing this list.')
        return plan

    for candidate in plan['remove']:
        current_id = runner(
            ['docker', 'image', 'inspect', candidate.reference, '--format', '{{.Id}}']
        )
        if current_id != candidate.image_id:
            raise ImageRetentionError(
                f'Rollback tag changed after review: {candidate.reference}'
            )
        if image_has_containers(candidate.image_id, runner):
            raise ImageRetentionError(
                f'Rollback image became used by a container: {candidate.reference}'
            )
        runner(['docker', 'image', 'rm', candidate.reference], timeout=120)
    print(f'Removed {len(plan["remove"])} reviewed rollback image tags.')
    return plan


def execute(*, keep=5, apply=False, runner=run_command, lock_root=None):
    try:
        with exclusive_operation_lock('backend-maintenance', root=lock_root):
            return _execute_unlocked(keep=keep, apply=apply, runner=runner)
    except OperationLockError as error:
        raise ImageRetentionError(str(error)) from error


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--keep', type=keep_count, default=5)
    parser.add_argument(
        '--apply',
        action='store_true',
        help='remove the listed tags; without this flag the command is read-only',
    )
    args = parser.parse_args()
    try:
        execute(keep=args.keep, apply=args.apply)
    except (ImageRetentionError, OSError, ValueError) as error:
        parser.exit(1, f'Backend image retention refused: {error}\n')


if __name__ == '__main__':
    main()
